-- Merge Skills Training's four selection tables into two.
--
--   skills_training_purposes + skills_training_qualifications
--       -> skills_training_options          (the list of choices; option_type says which list)
--   skills_training_profile_purposes + skills_training_profile_qualifications
--       -> skills_training_profile_options  (what each profile picked)
--
-- The two lookups had identical columns, and so did the two link tables, so one table of each
-- kind is enough. The "other, please specify" text is now one column, other_specification
-- (the same name ofw_profile_request_types already uses).
--
-- Normalization: option_type is stored only on the option and never copied onto the link
-- table, so nothing there can disagree with it (the link table reaches the type through
-- option_id).
--
-- Uniqueness:
--   * (option_type, option_name) is unique, so a name cannot repeat within a type.
--   * A profile cannot pick the same ordinary option twice (partial unique index). A profile
--     may still have several "Other" entries, each with its own text -- the application relies
--     on that, so there is no blanket unique rule on (profile, option).
--
-- Existing rows are copied over first (ids are new; the application matches options by name),
-- then the four old tables are dropped.
--
-- Run this at the same time as the updated PHP (modules/skills_training.php): the old code reads
-- the old tables, the new code reads the new ones. Run it ONCE -- it is not safe to repeat (the
-- old tables are gone afterwards). It is a single transaction, so if anything fails, nothing
-- is changed.

BEGIN;

CREATE TYPE skills_training_option_type_enum AS ENUM ('Purpose', 'Qualification');

CREATE TABLE skills_training_options (
    option_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    option_type  skills_training_option_type_enum NOT NULL,
    option_name  varchar(255) NOT NULL,
    is_active    boolean NOT NULL DEFAULT true,
    created_at   timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_skills_training_options_type_name UNIQUE (option_type, option_name)
);

CREATE TABLE skills_training_profile_options (
    profile_option_id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skills_training_profile_id  bigint NOT NULL,
    option_id                   bigint NOT NULL,
    other_specification         varchar(255),
    CONSTRAINT fk_st_profile_options_profile
        FOREIGN KEY (skills_training_profile_id)
        REFERENCES skills_training_profiles (skills_training_profile_id) ON DELETE CASCADE,
    CONSTRAINT fk_st_profile_options_option
        FOREIGN KEY (option_id)
        REFERENCES skills_training_options (option_id) ON DELETE CASCADE
);

CREATE INDEX idx_st_profile_options_profile_id ON skills_training_profile_options (skills_training_profile_id);
CREATE INDEX idx_st_profile_options_option_id  ON skills_training_profile_options (option_id);
CREATE UNIQUE INDEX uq_st_profile_options_plain
    ON skills_training_profile_options (skills_training_profile_id, option_id)
    WHERE other_specification IS NULL;

-- The lists of choices (qualifications first, then purposes, each in its old id order).
INSERT INTO skills_training_options (option_type, option_name, is_active, created_at, updated_at)
SELECT 'Qualification', qualification_name, is_active, created_at, updated_at
FROM skills_training_qualifications
ORDER BY qualification_id;

INSERT INTO skills_training_options (option_type, option_name, is_active, created_at, updated_at)
SELECT 'Purpose', purpose_name, is_active, created_at, updated_at
FROM skills_training_purposes
ORDER BY purpose_id;

-- What each profile picked, matched to the new options by type and name.
INSERT INTO skills_training_profile_options (skills_training_profile_id, option_id, other_specification)
SELECT pq.skills_training_profile_id, o.option_id, pq.other_qualification
FROM skills_training_profile_qualifications pq
JOIN skills_training_qualifications q ON q.qualification_id = pq.qualification_id
JOIN skills_training_options o ON o.option_type = 'Qualification' AND o.option_name = q.qualification_name
ORDER BY pq.profile_qualification_id;

INSERT INTO skills_training_profile_options (skills_training_profile_id, option_id, other_specification)
SELECT pp.skills_training_profile_id, o.option_id, pp.other_purpose
FROM skills_training_profile_purposes pp
JOIN skills_training_purposes pu ON pu.purpose_id = pp.purpose_id
JOIN skills_training_options o ON o.option_type = 'Purpose' AND o.option_name = pu.purpose_name
ORDER BY pp.profile_purpose_id;

DROP TABLE skills_training_profile_qualifications;
DROP TABLE skills_training_profile_purposes;
DROP TABLE skills_training_qualifications;
DROP TABLE skills_training_purposes;

COMMIT;
