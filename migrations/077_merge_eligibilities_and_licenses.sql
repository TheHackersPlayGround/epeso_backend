-- Merge the applicant's eligibilities and professional licenses into one table.
--
-- Both tables had the same shape: a link to the applicant, a name, and one date. They become
-- applicant_credentials, with credential_type telling the two apart. Each date keeps its own
-- meaning, so there are two date columns:
--   date_taken   -- used by an 'Eligibility' (Civil Service exam date)
--   valid_until  -- used by a 'License'      (Professional license expiry)
-- A CHECK rule keeps each type to its own date, so a bad row cannot be saved.
--
-- Existing rows are copied over first, then the two old tables are dropped.
--
-- Run this at the same time as the updated PHP (modules/employment.php): the old code reads
-- the old tables, the new code reads applicant_credentials. Run it ONCE -- it is not safe to
-- repeat (the old tables are gone afterwards). It is a single transaction, so if anything
-- fails, nothing is changed.

BEGIN;

CREATE TYPE credential_type_enum AS ENUM ('Eligibility', 'License');

CREATE TABLE applicant_credentials (
    credential_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    beneficiary_id   bigint NOT NULL,
    credential_type  credential_type_enum NOT NULL,
    credential_name  varchar(255) NOT NULL,
    date_taken       date,
    valid_until      date,
    CONSTRAINT fk_applicant_credentials_beneficiary
        FOREIGN KEY (beneficiary_id) REFERENCES beneficiaries (beneficiary_id),
    -- an eligibility has no expiry date; a license has no date taken
    CONSTRAINT chk_applicant_credentials_dates CHECK (
        (credential_type = 'Eligibility' AND valid_until IS NULL)
        OR (credential_type = 'License' AND date_taken IS NULL)
    )
);

CREATE INDEX idx_applicant_credentials_beneficiary_id ON applicant_credentials (beneficiary_id);

INSERT INTO applicant_credentials (beneficiary_id, credential_type, credential_name, date_taken)
SELECT beneficiary_id, 'Eligibility', eligibility_name, date_taken
FROM eligibilities
ORDER BY eligibility_id;

INSERT INTO applicant_credentials (beneficiary_id, credential_type, credential_name, valid_until)
SELECT beneficiary_id, 'License', license_name, valid_until
FROM licenses
ORDER BY license_id;

DROP TABLE eligibilities;
DROP TABLE licenses;

COMMIT;
